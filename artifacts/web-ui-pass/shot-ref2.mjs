import { chromium } from 'playwright'
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const notes = []
await page.goto('http://127.0.0.1:4173/', { waitUntil: 'networkidle' })
await page.waitForTimeout(400)
notes.push('h1 ' + await page.locator('.hero h1').innerText())
const welcome = await page.locator('.home-welcome-top__card').boundingBox()
notes.push('welcome ' + JSON.stringify(welcome))
await page.screenshot({ path: 'artifacts/web-ui-pass/ref-desktop-top.png' })
await page.locator('.mood', { hasText: 'Компания' }).click()
await page.waitForTimeout(400)
notes.push('mode ' + page.url())
await page.goto('http://127.0.0.1:4173/', { waitUntil: 'domcontentloaded' })
await page.locator('.mood', { hasText: '18+' }).click()
await page.waitForTimeout(300)
notes.push('adult dialog ' + await page.locator('.adult-confirm, [class*=adult]').count())
notes.push('still home ' + page.url())
await page.keyboard.press('Escape')
await page.locator('button.nav-link', { hasText: 'Избранное' }).click()
await page.waitForTimeout(300)
notes.push('fav overlay ' + await page.locator('.premium-overlay').count() + ' url ' + page.url())
await page.keyboard.press('Escape')
await page.goto('http://127.0.0.1:4173/games', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(400)
const games = await page.evaluate(() => ({
  home: !!document.querySelector('.gnh-home-ref'),
  theme: getComputedStyle(document.querySelector('.gnh-theme-background')).visibility,
  cards: document.querySelectorAll('.games-grid__card, .games-page').length,
}))
notes.push('games ' + JSON.stringify(games))
const phone = await browser.newPage({ viewport: { width: 390, height: 844 } })
await phone.goto('http://127.0.0.1:4173/', { waitUntil: 'networkidle' })
await phone.waitForTimeout(300)
await phone.screenshot({ path: 'artifacts/web-ui-pass/ref-phone-top.png' })
await phone.locator('.menu-button').click()
await phone.waitForTimeout(200)
const menu = await phone.locator('.gnh-menu.is-open').count()
notes.push('menu ' + menu)
await phone.screenshot({ path: 'artifacts/web-ui-pass/ref-phone-menu.png' })
await browser.close()
console.log(notes.join('\n'))
