begin;

create table if not exists public.mafia_rooms (
  id text primary key,
  code text not null unique,
  host_token text not null,
  phase text not null default 'lobby'
    check (phase in ('lobby', 'reveal', 'night', 'discussion', 'vote', 'finished')),
  round integer not null default 0 check (round >= 0),
  phase_ends_at bigint,
  event_key text not null default 'rain',
  public_message text not null default 'Соберите город за одним столом.',
  winner text check (winner is null or winner in ('city', 'mafia', 'neutral')),
  created_at bigint not null,
  updated_at bigint not null
);

create table if not exists public.mafia_players (
  id text primary key,
  room_id text not null references public.mafia_rooms(id) on delete cascade,
  token text not null unique,
  name text not null,
  avatar integer not null default 0 check (avatar between 0 and 7),
  is_host boolean not null default false,
  alive boolean not null default true,
  role text check (role is null or role in ('don', 'mafia', 'detective', 'doctor', 'maniac', 'citizen')),
  team text check (team is null or team in ('city', 'mafia', 'neutral')),
  revealed boolean not null default false,
  private_note text not null default '',
  joined_at bigint not null,
  unique (room_id, name)
);

create table if not exists public.mafia_actions (
  id bigint generated by default as identity primary key,
  room_id text not null references public.mafia_rooms(id) on delete cascade,
  round integer not null check (round >= 1),
  phase text not null check (phase in ('night', 'vote')),
  player_id text not null references public.mafia_players(id) on delete cascade,
  action_kind text not null check (action_kind in ('kill', 'investigate', 'protect', 'solo_kill', 'lynch')),
  target_player_id text not null references public.mafia_players(id) on delete cascade,
  created_at bigint not null,
  unique (room_id, round, phase, player_id)
);

create table if not exists public.mafia_events (
  id bigint generated by default as identity primary key,
  room_id text not null references public.mafia_rooms(id) on delete cascade,
  round integer not null check (round >= 0),
  kind text not null,
  message text not null,
  created_at bigint not null
);

create index if not exists idx_mafia_rooms_updated_at on public.mafia_rooms(updated_at);
create index if not exists idx_mafia_players_room on public.mafia_players(room_id);
create index if not exists idx_mafia_actions_turn on public.mafia_actions(room_id, round, phase);
create index if not exists idx_mafia_events_room_id on public.mafia_events(room_id, id);

alter table public.mafia_rooms enable row level security;
alter table public.mafia_players enable row level security;
alter table public.mafia_actions enable row level security;
alter table public.mafia_events enable row level security;

commit;

revoke all on table public.mafia_rooms from public;
revoke all on table public.mafia_players from public;
revoke all on table public.mafia_actions from public;
revoke all on table public.mafia_events from public;
revoke all on sequence public.mafia_actions_id_seq from public;
revoke all on sequence public.mafia_events_id_seq from public;

grant all on table public.mafia_rooms to current_user;
grant all on table public.mafia_players to current_user;
grant all on table public.mafia_actions to current_user;
grant all on table public.mafia_events to current_user;
grant all on sequence public.mafia_actions_id_seq to current_user;
grant all on sequence public.mafia_events_id_seq to current_user;

